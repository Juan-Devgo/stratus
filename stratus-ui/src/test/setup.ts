import "@testing-library/jest-dom/vitest";

// jsdom no implementa window.matchMedia y Sonner lo usa para detectar el tema del sistema.
if (!window.matchMedia) {
  window.matchMedia = (query: string): MediaQueryList => ({
    matches: false,
    media: query,
    onchange: null,
    addEventListener: () => {},
    removeEventListener: () => {},
    addListener: () => {},
    removeListener: () => {},
    dispatchEvent: () => false,
  });
}
